filled = 0
skipped_filled = 0
missing = []

seed_texts.each do |slug, blocks|
  # `unscoped` — по аналогии с zhk:seed: мягко удалённый ЖК должен
  # находиться, иначе прогон молча создал бы ощущение, что записи нет.
  complex = ResidentialComplex.unscoped.find_by(slug: slug)

  if complex.nil?
    missing << slug
    next
  end

  # Идемпотентность: текст ставим ТОЛЬКО в пустой `body_blocks`.
  #
  # Здесь, в отличие от `residential_complexes.rb`, проверка идёт по
  # `present?`, а не строго по `nil`. Причина в семантике поля: пустой
  # `address_patterns` — осмысленное решение редактора (админка сознательно
  # позволяет стереть паттерны), а пустой `body_blocks` осмысленным
  # состоянием не бывает — ЖК без текста просто выпадает из sitemap
  # (`ResidentialComplex.sitemap_ready`). Редактор текст правит, а не
  # обнуляет, поэтому «пусто» здесь однозначно значит «ещё не заливали».
  if complex.body_blocks.present?
    skipped_filled += 1
    next
  end

  # Пре-рендер body_html/body_plain делает before_save из
  # RendersLandingBlocks — руками их не трогаем, иначе проекции разъедутся.
  complex.body_blocks = blocks
  complex.save!
  filled += 1
end

