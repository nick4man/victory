# Явная связь сотрудника CRM с его аккаунтом в Telegram (09.08.26).
#
# До сих пор связь держалась на совпадении `telegram_users.email` с
# `users.email` — угадывание, которое на проде работает у двоих агентов из
# четырёх. У одного в TG заведён `Oks07@yandex.ru`, а в CRM `oks07rzn@gmail.com`
# — сорок объектов оказались недостижимы для уведомлений просто из-за разных
# почтовых ящиков одного человека.
#
# Совпадение email вдобавок ненадёжно по существу: почту меняют, а один и тот
# же ящик может быть указан у двух записей. Поэтому связь — отдельной колонкой,
# устанавливается явным подтверждением директора.
#
# Направление (users → telegram_users, а не наоборот) выбрано потому, что
# `telegram_users` наполняется auto-discovery из входящих сообщений и содержит
# записи без соответствия в CRM (сторонние участники рабочих чатов). Обратная
# ссылка потребовала бы nullable-колонки в таблице, где большинство строк её бы
# не имели.
#
# on_delete: :nullify — удаление TG-аккаунта не должно уносить учётку
# сотрудника. Индекс unique: один телеграм принадлежит одному сотруднику,
# попытка связать его со вторым должна падать, а не создавать двусмысленность
# при рассылке.
class AddTelegramUserIdToUsers < ActiveRecord::Migration[7.1]
  def change
    add_reference :users, :telegram_user,
                  null: true,
                  index: { unique: true },
                  foreign_key: { on_delete: :nullify }
  end
end
