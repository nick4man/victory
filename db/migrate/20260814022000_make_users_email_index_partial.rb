# users.email — `NOT NULL DEFAULT ''` под обычным уникальным индексом. Форма
# досталась от Devise, который в проекте отключён, и до сих пор была безобидна:
# все учётки заводились с почтой.
#
# Приём собственника от агента её ломает. Самый частый ответ — одно имя и
# телефон («Светлана 9001234567»), почты нет, и OwnerLinker#build_attrs
# оставляет колонку в дефолте. Пустых строк индекс допускает ровно одну:
# первый телефонный собственник заводится, каждый следующий падает на
# RecordNotUnique, и агент видит «не удалось завести клиента» без объяснимой
# причины. Ни один спек этого не ловит — DatabaseCleaner чистит базу между
# примерами, и в каждом таком собственник всегда один.
#
# Частичный индекс сохраняет уникальность настоящих адресов и снимает
# ограничение с пустых. На проде 23 учётки, из них 0 с `email = ''` — накатка
# конфликтов не встретит.
class MakeUsersEmailIndexPartial < ActiveRecord::Migration[7.1]
  def up
    remove_index :users, :email
    add_index :users, :email, unique: true, where: "email <> ''"
  end

  def down
    remove_index :users, :email
    add_index :users, :email, unique: true
  end
end
