# Журнал прогонов сборщика (services/zhk-registry) — сколько наблюдений
# каждый источник ОТПРАВИЛ за один прогон `run.py`.
#
# Не путать с `zhk_observations`: там — строки, которые реально
# СОЗДАЛИСЬ (`Zhk::Ingest` пишет строку только на новый или изменившийся
# контент, повторная доставка того же самого — `:duplicate`, строки не
# добавляет вовсе). Каталог новостроек Рязани почти статичен — в обычную
# неделю меняются один-два ЖК из нескольких десятков, — поэтому число
# строк `zhk_observations` за неделю почти всегда околонулевое ДАЖЕ
# когда источник работает штатно. Если бы детектор молчащего источника
# (`Zhk::RunSummary`) сравнивал с этим числом, он бы выключал сам себя
# в любую обычную неделю (порог `SILENCE_RATIO` вырождается в «строго
# ноль» при малом ожидании) — ровно так и было устроено до этого круга
# правок.
#
# Здесь же — то, что источник в принципе НАШЁЛ и ПОПЫТАЛСЯ применить в
# этом прогоне (после вычитания `:invalid`, см. `run.py:run_source`),
# независимо от того, изменилось ли что-то по сравнению с прошлым
# разом. Это число из недели в неделю стабильно близко к размеру всего
# каталога источника (десятки строк, не единицы) — сравнение прогон к
# прогону на нём осмысленно, и `SILENCE_RATIO`/окно сравнения начинают
# значить то, что написано в докстринге `Zhk::RunSummary`.
class CreateZhkIngestRuns < ActiveRecord::Migration[8.1]
  def change
    create_table :zhk_ingest_runs do |t|
      t.string   :source, null: false
      t.integer  :count,  null: false
      t.datetime :ran_at, null: false
      t.timestamps
    end

    add_index :zhk_ingest_runs, %i[source ran_at]
  end
end
