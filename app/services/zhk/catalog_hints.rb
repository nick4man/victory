# frozen_string_literal: true

module Zhk
  # ЖК, названные в карточках нашего же каталога, но отсутствующие в
  # справочнике. Четвёртый источник расхождений — и он отличается от
  # остальных трёх: это ПОДСКАЗКА, а не факт. Имя ЖК в карточке объекта —
  # рекламный текст риэлтора, а не проектная декларация застройщика,
  # поэтому здесь нет ни черновика ЖК, ни записи в `zhk_facts` — только
  # строка отчёта для редактора, который сам решает, заводить комплекс или
  # нет. Ровно так 07.09.26 руками нашлись «Северный», «Маргелов»,
  # «Пожарский», «Лето» и «Голландия» — они годами лежали в карточках
  # каталога до того, как попали в справочник.
  #
  # Опознание уже известных ЖК — строго через `Zhk::Matcher.call`, тот же
  # матчер, что и в применяторе фактов и подборе привязки: он прошёл пять
  # кругов правок (кавычки, приставка «ЖК», регистр, ё/е, разные ЖК одного
  # застройщика через точку, город, soft-delete). Своя сверка строк здесь
  # неизбежно окажется слабее уже отлаженной — заводить её вредно.
  module CatalogHints
    # Имя идёт после «ЖК» (кавычки — опционально) и обязано начинаться с
    # заглавной кириллической буквы. Нижняя граница длины (минимум 3 буквы
    # исходной последовательности) отсекает однобуквенный шум («ЖК А, кв.
    # 12») уже на уровне регэкспа: капитал-класс задаёт первый символ,
    # квантификатор `{2,40}` требует ещё хотя бы 2. Числовой «шум» («ЖК
    # 2026 году», «Сдача в ЖК 5») отсекается тем же способом: первый символ
    # обязан быть буквой, а не цифрой — год или номер очереди сразу после
    # «ЖК» такой проверки не проходит. Верхняя граница (40) режет случай,
    # когда за «ЖК» через запятую идёт хвост предложения, а не название —
    # без неё регэксп жадно захватил бы половину описания до следующего
    # разделителя.
    #
    # Точка в классе терминаторов НАМЕРЕННО убрана (круг правок 1, найдено
    # ревью): у составных названий вроде «Голландия. Парковый квартал» она
    # стоит ВНУТРИ имени, а квантификатор ленивый — с точкой-терминатором
    # разбор останавливался на первой же внутренней точке и отдавал
    # усечённое «Голландия», для которого матчер (правомерно — он и должен
    # отличать «Парковый квартал» от «Верхний сад») не находил совпадения,
    # и уже заведённый ЖК попадал в подсказки как новый. Точка при этом
    # остаётся в теле имени (`[...\-.]`), поэтому составные названия
    # разбираются целиком. Плата за это — редкий случай, когда голое (без
    # кавычек) имя стоит в самом конце текста и обрывается точкой конца
    # предложения без другого терминатора следом: такое упоминание просто
    # не найдётся вовсе, вместо усечения. Пропуск дешевле повторной порчи
    # составного имени: пропущенную находку можно поймать следующим
    # прогоном, а ложную подсказку про уже заведённый ЖК — только руками.
    MENTION_RX = /Ж[Кк]\s*[«"]?\s*([А-ЯЁ][А-Яа-яёЁ0-9\s\-.]{2,40}?)\s*[»",;!?\n]/

    # Обороты речи, которые регэксп иногда всё же захватывает как «имя»,
    # если первое слово после «ЖК» случайно начинается с заглавной буквы
    # (начало предложения, опечатка регистра). Список — не грамматика, а
    # накопленный при ручном разборе черновиков реестра шум.
    STOP_WORDS = %w[и или до от рядом около близко можно уточняйте].freeze

    module_function

    def call
      hints = Hash.new { |h, k| h[k] = { property_ids: [], sample_address: nil, raw_name: nil } }
      # Кэшируем ТОЛЬКО вердикт по имени — `Matcher.call(name:, city:)` без
      # адреса задействует исключительно первый канал матчера (точное
      # совпадение нормализованного имени с записью справочника), а он
      # правда одинаков для всех карточек с одним и тем же (город, имя):
      # имя ЖК самодостаточно, адрес конкретной карточки на этот канал не
      # влияет никак.
      #
      # Адресный канал в кэш НЕ идёт (круг правок 1, найдено ревью на
      # воспроизводимом прогоне) — он чувствителен к адресу КОНКРЕТНОЙ
      # карточки, а не к имени: если одна карточка с именем «Стройка»
      # случайно адресом попадает в чужой `address_patterns` («Легенда» на
      # той же улице), это НЕ значит, что другая карточка с тем же именем
      # «Стройка», но по другому адресу, тоже «уже известна» — она обычная
      # незаведённая находка. Кэш по имени применил бы вердикт первой
      # карточки ко второй и молча потерял бы настоящую находку — а это
      # дороже лишнего запроса: пропавшую подсказку никто не заметит,
      # лишний SELECT по паре десятков строк справочника города — не
      # проблема (тот самый смысл ремарки ревью: «адресный канал зови
      # каждый раз — он и так ограничен пулом города, а не всем
      # каталогом»).
      known_by_name = {}
      # Мягко удалённые — отдельная проверка, не через Matcher: тот
      # намеренно не отличает soft-deleted от «никогда не существовал»
      # (это его контракт — сигнал «заведи черновик»), а нам здесь нужно
      # ИМЕННО отличить: редактор мог удалить ЖК осознанно, и не в нашей
      # власти считать его повторной находкой на каждом прогоне. Список
      # загружаем один раз на весь вызов, а не на упоминание.
      deleted_by_city = deleted_names_by_city

      candidate_rows.each do |id, title, description, address, city|
        city = city.presence || 'Рязань'
        names_in("#{title} #{description}").each do |name|
          normalized = Matcher.normalize(name)
          next if normalized.blank?
          next if deleted_by_city[city]&.include?(normalized)

          key = [city, normalized]
          known_by_name_hit = known_by_name.fetch(key) do
            known_by_name[key] = Matcher.call(name: name, city: city).present?
          end
          next if known_by_name_hit
          # Адресный канал — без кэша и с реальным адресом ЭТОЙ карточки,
          # см. комментарий у объявления `known_by_name` выше.
          next if Matcher.call(name: name, city: city, address: address).present?

          bucket = hints[key]
          bucket[:raw_name] ||= name
          bucket[:property_ids] << id
          bucket[:sample_address] ||= address
        end
      end

      hints.values.map { |data| { name: data[:raw_name], property_ids: data[:property_ids], sample_address: data[:sample_address] } }
    end

    def names_in(text)
      text.to_s.scan(MENTION_RX).flatten.filter_map do |raw|
        name = raw.strip.squeeze(' ')
        next if name.blank?
        next if STOP_WORDS.include?(name.split.first.to_s.downcase)

        name
      end.uniq
    end

    # Мягко удалённые ЖК по городам, нормализованные тем же способом, что
    # и матчер (`Matcher.normalize`) — переиспользуем чужую нормализацию, а
    # не изобретаем свою сверку: это то же самое сравнение, что делает
    # матчер внутри, просто на противоположном (удалённом) срезе таблицы,
    # к которому у самого матчера нет доступа по определению его контракта.
    def deleted_names_by_city
      ResidentialComplex.unscoped.deleted.pluck(:city, :name)
                        .group_by(&:first)
                        .transform_values { |rows| rows.map { |(_city, name)| Matcher.normalize(name) }.to_set }
    end

    # Узкая выборка вместо полного каталога в память: у объекта, чьи
    # title/description вообще не содержат заглавную «Ж», регэксп заведомо
    # не сработает (первый символ группы — обязательно заглавная буква
    # кириллицы, но «ЖК» тем более начинается именно с заглавной «Ж» по
    # построению MENTION_RX). LIKE, а не ILIKE — сравнение по байтам, а не
    # через регистронезависимое сравнение локали, которое на кириллице
    # ненадёжно; сужение честное (без ложных пропусков), просто не всегда
    # максимально узкое, если письменность содержит другие слова на «Ж».
    def candidate_rows
      Property.where('title LIKE :m OR description LIKE :m', m: '%Ж%')
              .pluck(:id, :title, :description, :address, :city)
    end
  end
end
