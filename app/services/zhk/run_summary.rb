# frozen_string_literal: true

module Zhk
  # Сводка одного прогона службы сбора (`services/zhk-registry`) и
  # детектор молчащего источника.
  #
  # Главный тихий отказ этой системы — не падение парсера (это уже
  # обрабатывается адаптером и `run.py`: дохлая ссылка или обвал одного
  # источника не должны прерывать обход остальных), а его МОЛЧАНИЕ:
  # чужой сайт переверстали, `discover()` находит ноль карточек,
  # исключений при этом нет вовсе — снаружи это неотличимо от источника,
  # у которого за неделю правда ничего не изменилось. Тот же класс
  # проблемы уже встречался на стороне `zhk_price_points`: ряд цен там
  # хранит ИЗМЕНЕНИЯ, а не наблюдения, и плоский участок графика
  # постфактум неотличим от мёртвого парсера. Здесь мы ловим разницу на
  # входе, пока она ещё видна, а не пытаемся распознать задним числом.
  #
  # ## Сравниваем прогон с прогоном, а НЕ с `zhk_observations` (круг правок 1)
  #
  # Первая версия этого детектора сравнивала `counts` (сколько наблюдений
  # источник ОТПРАВИЛ в этом прогоне) с числом строк `zhk_observations`
  # за прошлую неделю. Это была ошибка в основании: `Zhk::Ingest` создаёт
  # строку `ZhkObservation` только на новый или изменившийся контент —
  # повторная доставка того же самого получает `:duplicate` и строки не
  # добавляет вовсе. Каталог новостроек Рязани почти статичен (в обычную
  # неделю меняются один-два ЖК из нескольких десятков), поэтому
  # ожидаемое число СТРОК за неделю почти всегда околонулевое даже когда
  # источник работает штатно — `previous_week_count` был близок к нулю
  # почти всегда, `next if expected.zero?` срабатывал почти на каждом
  # прогоне, и детектор выключал сам себя ровно тогда, когда сравнивать
  # было бы важнее всего.
  #
  # Верное сравнение — таблица `ZhkIngestRun`: отдельный журнал, куда
  # `call` пишет ровно то число, которое пришло в `counts` (сколько
  # источник НАШЁЛ и ПОПЫТАЛСЯ применить в этом прогоне, до какой-либо
  # дедупликации по контенту на Rails-стороне). Это число из недели в
  # неделю стабильно близко к размеру всего каталога источника — десятки,
  # а не единицы, — и сравнение прогон к прогону на нём осмысленно:
  # `SILENCE_RATIO` и окно сравнения значат ровно то, что написано ниже,
  # а не вырождаются в «строго ноль».
  #
  # ## Два правила, а не одно (круг правок 2)
  #
  # `silent_sources` — это ДВА разных правила, а не одно, и оба работают
  # одновременно:
  #
  #   1. **Фронтовое (переход).** `dropped_sharply?` — count этого
  #      прогона кратно (порог `SILENCE_RATIO`) меньше ПРЕДЫДУЩЕГО.
  #      Ловит МОМЕНТ поломки — сайт переверстали именно сейчас.
  #   2. **Уровневое (состояние).** `persistently_silent?` — count этого
  #      прогона РОВНО НОЛЬ, и у источника есть хотя бы один прошлый
  #      прогон (неважно, каким было его значение). Ловит СОСТОЯНИЕ
  #      «источник продолжает молчать», а не только момент, когда он
  #      замолчал.
  #
  # Без второго правила первая версия этого детектора ловила ровно ОДИН
  # прогон из всех, где источник на самом деле мёртв, — и то по случайности:
  #
  #   - **Молчание живёт неделю, а не до починки.** Источник молчит уже
  #     вторую неделю подряд: прошлый прогон тоже был 0, `dropped_sharply?`
  #     сравнивает 0 с 0 (`expected.zero?` → `next`) и ничего не находит —
  #     источник сравнивается сам с собой на дне и «выглядит стабильным».
  #     Если СВОДКА ИМЕННО ТОЙ недели, когда сработало фронтовое правило,
  #     не дошла (Telegram недоступен, `TELEGRAM_STAFF_CHAT_ID` не
  #     настроен — ровно тот отказ, который решает `delivered` в
  #     круге правок 1) — редактор не узнал бы вообще НИКОГДА: тревога
  #     живёт один прогон, а справочник мёртв неограниченно долго.
  #   - **Источник, мёртвый с рождения, не ловится вообще.** Если count
  #     был 0 с самого первого прогона (адаптер сломан ещё до первого
  #     живого запуска), `previous_run_count` всегда 0, `expected.zero?`
  #     всегда пропускает — `dropped_sharply?` не сработает НИКОГДА,
  #     потому что не было МОМЕНТА перехода из «жив» в «мёртв».
  #
  # `persistently_silent?` — тревога на КАЖДОМ прогоне, пока count не
  # отклеится от нуля, начиная со ВТОРОГО прогона источника (первый —
  # «первый раз в жизни», см. ниже, ему сравнивать не с чем). Порог здесь
  # не 30%, а строго ноль: источник, отдающий хоть что-то (даже заметно
  # меньше обычного), уже покрыт фронтовым правилом на самом переходе —
  # уровневое правило нужно только для «уже ноль и остаётся нулём».
  #
  # ## Сколько прогонов молчания считаем сбоем
  #
  # Один — но это относится к ФРОНТОВОМУ правилу: тревога срабатывает
  # уже на первом прогоне с аномально низким count относительно
  # предыдущего, не ждёт повторения. Две причины:
  #
  #   1. Ожидание не бесплатно, а ложная тревога дёшева. Обход еженедельный
  #      (см. `crontab.example`) — если бы детектор ждал второго подряд
  #      молчания, справочник к моменту сигнала уже минимум неделю тихо
  #      терял бы данные, а смысл детектора именно в том, чтобы поймать
  #      это ДО того, как накопится, а не подтвердить задним числом. Цена
  #      ложного срабатывания — одно сообщение в TG, которое редактор
  #      проверяет за минуту.
  #   2. Транзиентные сбои ОТПРАВКИ (сеть моргнула на одном батче, сервер
  #      разово ответил 503) отфильтрованы РАНЬШЕ этого класса, на
  #      стороне `run.py` (`send_with_retry`/`call_with_retry`) — до
  #      того, как число вообще попадёт в `counts`. Если после ретраев
  #      источник всё равно отдал в разы меньше обычного — это уже не шум
  #      одного запроса, а сигнал про сам источник: переверстали,
  #      заблокировали User-Agent, сайт лёг целиком.
  #
  # УРОВНЕВОЕ правило намеренно повторяется КАЖДЫЙ прогон, пока
  # источник не отклеится от нуля — оно и заведено ради противоположного
  # свойства: тревога обязана переживать пропуск одной сводки, а не
  # погаснуть после единственного сообщения.
  #
  # ## Источник, который молчит первый раз в жизни
  #
  # Не считается молчащим ни по одному из правил: оба требуют хотя бы
  # один ПРЕДЫДУЩИЙ прогон (`ZhkIngestRun.for_source(source).exists?` /
  # `previous_run_count` не `nil`), иначе сравнивать не с чем. У только
  # что подключённого источника (адаптер добавили, ни одного прогона ещё
  # не было) низкий или нулевой count — стартовое состояние, а не
  # аномалия. Начиная со ВТОРОГО прогона источник уже имеет историю (пусть
  # и из одной, возможно нулевой, строки) — и если он мёртв с рождения,
  # уровневое правило подхватит его именно тогда, а не будет ждать вечно.
  module RunSummary
    # Порог фронтового правила: меньше 30% от объёма ПРЕДЫДУЩЕГО прогона —
    # это уже не обычный разброс выдачи сайта (на прогон к прогону одного
    # и того же каталога он заметно уже), а вероятная поломка обхода.
    # Подобран с запасом в сторону «не дёргать редактора по пустякам»:
    # настоящий сбой (переверстка, бан User-Agent, обвал сайта целиком)
    # обычно роняет count к нулю или близко к нему, а не на условные
    # 40-50%.
    SILENCE_RATIO = 0.3

    module_function

    # @return [Array<String>] источники, молчащие ПО ЛЮБОМУ из двух
    # правил — фронтовому (переход) или уровневому (состояние), см.
    # докстринг модуля.
    def silent_sources(counts)
      counts.filter_map do |source, current|
        source if persistently_silent?(source, current) || dropped_sharply?(source, current)
      end
    end

    # @return [String] текст сводки для TG-канала сотрудников. Пишет
    # текущий прогон в журнал ПОСЛЕ того, как посчитан `silent_sources` —
    # иначе источник сравнивался бы сам с собой, а не с предыдущим
    # прогоном.
    #
    # Имя источника ЭКРАНИРУЕТСЯ: `counts` приходит из внешнего запроса
    # (`POST /webhooks/zhk_ingest/summary`), а сообщение уходит в TG с
    # `parse_mode: 'HTML'` (`Telegram::Client#send_message`). Без
    # экранирования источник с именем вроде `"<b>"` либо сломал бы
    # разметку сообщения, либо TG вовсе отверг бы отправку как невалидный
    # HTML — тревога о молчащем источнике не должна зависеть от того,
    # какие символы оказались в ключах `counts`.
    def call(counts)
      lines = ["Обход справочника ЖК — #{Time.zone.today.strftime('%d.%m.%y')}"]
      counts.each { |source, count| lines << "#{ERB::Util.html_escape(source)}: #{count.to_i}" }

      silent = silent_sources(counts)
      if silent.any?
        escaped = silent.map { |source| ERB::Util.html_escape(source) }
        lines << "🚨 молчат: #{escaped.join(', ')} — вероятно, сменилась вёрстка или источник недоступен"
      end

      record_run(counts)

      lines.join("\n")
    end

    # Уровневое правило (см. докстринг модуля): этот прогон — строго
    # ноль, и у источника уже есть история (хотя бы один прошлый прогон,
    # неважно с каким значением). Срабатывает КАЖДЫЙ раз, пока count не
    # отклеится от нуля — включая повтор недели за неделей и первый же
    # прогон источника, мёртвого с рождения.
    def persistently_silent?(source, current)
      current.to_i.zero? && ZhkIngestRun.for_source(source).exists?
    end

    # Фронтовое правило (см. докстринг модуля): этот прогон кратно
    # меньше ПРЕДЫДУЩЕГО. `expected.zero?` не по недосмотру — источник,
    # чей предыдущий прогон уже был нулём, покрыт `persistently_silent?`
    # выше, а не этим правилом (0 * SILENCE_RATIO = 0, и никакое
    # неотрицательное `current` не может быть меньше нуля — правило и
    # так математически молчало бы, проверка лишь делает это явным).
    def dropped_sharply?(source, current)
      expected = previous_run_count(source)
      return false if expected.nil? || expected.zero?

      current.to_i < expected * SILENCE_RATIO
    end

    # @return [Integer, nil] count предыдущего прогона того же источника,
    # `nil` — если прогонов ещё не было вовсе (см. докстринг про новый
    # источник).
    def previous_run_count(source)
      ZhkIngestRun.for_source(source).order(ran_at: :desc).first&.count
    end

    # Пишет по одной строке `ZhkIngestRun` на каждый источник этого
    # прогона — журнал, а не апдейт: следующий прогон сравнивает себя с
    # этой строкой через `previous_run_count` (последняя по `ran_at`), а
    # `persistently_silent?` — через сам факт её существования.
    def record_run(counts)
      now = Time.current
      counts.each { |source, count| ZhkIngestRun.create!(source: source, count: count.to_i, ran_at: now) }
    end
  end
end
