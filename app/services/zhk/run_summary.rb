# frozen_string_literal: true

module Zhk
  # Сводка одного прогона службы сбора (`services/zhk-registry`) и
  # детектор молчащего источника.
  #
  # Главный тихий отказ этой системы — не падение парсера (это уже
  # обрабатывается адаптером и `run.py`: дохлая ссылка или обвал одного
  # источника не должны прерывать обход остальных), а его МОЛЧАНИЕ:
  # чужой сайт переверстали, `discover()` находит ноль карточек,
  # исключений при этом нет вовсе — снаружи это неотличимо от источника,
  # у которого за неделю правда ничего не изменилось. Тот же класс
  # проблемы уже встречался на стороне `zhk_price_points`: ряд цен там
  # хранит ИЗМЕНЕНИЯ, а не наблюдения, и плоский участок графика
  # постфактум неотличим от мёртвого парсера. Здесь мы ловим разницу на
  # входе, пока она ещё видна, а не пытаемся распознать задним числом.
  #
  # ## Сколько прогонов молчания считаем сбоем
  #
  # Один. Тревога срабатывает уже на ПЕРВОМ прогоне с аномально низким
  # count, а не ждёт повторения на следующей неделе. Две причины:
  #
  #   1. Ожидание не бесплатно, а ложная тревога дёшева. Обход еженедельный
  #      (см. `crontab.example`) — если бы детектор ждал второго подряд
  #      молчания, справочник к моменту сигнала уже минимум неделю тихо
  #      терял бы данные, а смысл детектора именно в том, чтобы поймать
  #      это ДО того, как накопится, а не подтвердить задним числом. Цена
  #      ложного срабатывания — одно сообщение в TG, которое редактор
  #      проверяет за минуту.
  #   2. Транзиентные сбои (сеть моргнула на одном батче, сервер разово
  #      ответил 503) отфильтрованы РАНЬШЕ этого класса, на стороне
  #      `run.py` (ретрай 5xx перед тем, как число вообще попадёт в
  #      `counts`). Если после ретраев источник всё равно отдал в разы
  #      меньше обычного — это уже не шум одного запроса, а сигнал про
  #      сам источник: переверстали, заблокировали User-Agent, сайт лёг
  #      целиком.
  #
  # ## Источник, который молчит первый раз в жизни
  #
  # Не считается молчащим: `silent_sources` требует ненулевую историю
  # (`previous_week_count` > 0), иначе сравнивать не с чем. У только что
  # подключённого источника (адаптер добавили, ни одного прогона ещё не
  # было) низкий или нулевой count — стартовое состояние, а не аномалия;
  # объявлять катастрофой первый холодный обход значило бы наказывать
  # источник за то, что его вообще завели. Как только появится хотя бы
  # одна неделя истории, детектор начинает сравнивать как обычно —
  # включая случай, когда история появилась только вчера.
  module RunSummary
    # Порог: меньше 30% от объёма прошлой недели — это уже не обычный
    # разброс выдачи сайта (на дюжине ЖК Рязани он заметно уже), а
    # вероятная поломка обхода. Подобран с запасом в сторону «не дёргать
    # редактора по пустякам»: настоящий сбой (переверстка, бан
    # User-Agent, обвал сайта целиком) обычно роняет count к нулю или
    # близко к нему, а не на условные 40-50%.
    SILENCE_RATIO = 0.3

    module_function

    # @return [Array<String>] источники, отдавшие в этом прогоне кратно
    # меньше обычного — при условии, что для них вообще есть с чем
    # сравнивать (см. докстринг модуля про источник без истории).
    def silent_sources(counts)
      counts.filter_map do |source, current|
        expected = previous_week_count(source)
        next if expected.zero?

        source if current.to_i < expected * SILENCE_RATIO
      end
    end

    # @return [String] текст сводки для TG-канала сотрудников.
    def call(counts)
      lines = ["Обход справочника ЖК — #{Time.zone.today.strftime('%d.%m.%y')}"]
      counts.each { |source, count| lines << "#{source}: #{count}" }

      silent = silent_sources(counts)
      if silent.any?
        lines << "🚨 молчат: #{silent.join(', ')} — вероятно, сменилась вёрстка или источник недоступен"
      end

      lines.join("\n")
    end

    # Объём того же источника неделей раньше текущего прогона. Окно
    # 7-14 дней назад, а не «с начала времён»: обход еженедельный, а
    # значит «неделю назад» и есть предыдущий прогон — самое свежее
    # осмысленное сравнение. Более старая история намеренно не
    # учитывается: если объём выдачи источника дрейфует месяцами,
    # сравнение с позапрошлым обходом всё равно полезнее сравнения со
    # средним за произвольный период.
    def previous_week_count(source)
      ZhkObservation.for_source(source)
                    .where(fetched_at: 14.days.ago..7.days.ago)
                    .count
    end
  end
end
