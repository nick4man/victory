# frozen_string_literal: true

module Zhk
  # Расхождение — это запрос к фактам, а не хранимая сущность: отдельная
  # таблица держала бы производное состояние, которое разъезжается первым.
  #
  # Что считаем расхождением, а что шумом:
  #
  #   * `value: nil` — источник промолчал (поля не было в его данных), это
  #     отсутствие мнения, а не мнение «данных нет». Такую строку вообще
  #     не рассматриваем: сравнивать нечего, и она не должна ни превращать
  #     единственное реальное мнение в расхождение, ни попадать в `all`
  #     как «версия» поля. Пустая строка (в отличие от nil) — источник
  #     осмотрел поле и явно заявил пустоту; это утверждение, и оно может
  #     конфликтовать с непустым значением другого источника — считаем.
  #   * Одно и то же значение, по-разному отформатированное источником, —
  #     не расхождение: регистр («Монолитно-кирпичный» / «монолитно-
  #     кирпичный»), организационно-правовая форма застройщика («ГК
  #     Единство» / «Единство»), года со служебным суффиксом («2026» /
  #     «2026 г.»). Сравниваем НЕ сырые строки, а их нормализованную форму
  #     — см. `normalize`.
  #   * Если по полю высказался ровно один источник — расхождения нет по
  #     определению (не с чем спорить), и это следует из общей проверки
  #     «более одного различного нормализованного значения», а не из
  #     отдельной ветки — так надёжнее: спорных источников может быть и
  #     трое, где двое совпали, а третий один против них.
  #
  # Строгость — не как у Matcher: там лишнее совпадение опаснее
  # пропущенного (склеит разные объекты), здесь наоборот — пропущенное
  # расхождение хуже лишнего (молча применённая неверная фактура против
  # лишней ручной работы редактора). При сомнении нормализация НЕ
  # добавляется — расхождение остаётся видимым.
  module Discrepancies
    # Приставки, которые снимаем перед сравнением застройщика. Список
    # НАМЕРЕННО ограничен только маркетинговыми/обязательными по закону
    # словами — не «организационно-правовыми формами» вообще, это было
    # ошибкой круга правок 1. `developer` в справочнике хранит БРЕНД, под
    # которым продаётся ЖК, а не юрлицо по ДДУ (у «Пожарского» застройщик
    # по договору — ООО «Атом», а записано «Единство», потому что клиент
    # ищет по бренду) — поэтому снимать нужно ровно то, что бренд не
    # различает:
    #   * «ГК» («группа компаний») — маркетинговая приставка, идентичности
    #     не несёт;
    #   * «СЗ» («специализированный застройщик») — по 214-ФЗ обязателен
    #     для любого застройщика, поэтому тоже никого не отличает.
    # «ООО»/«АО»/«ЗАО»/«ОАО»/«ПАО»/«ИП» сюда НЕ ДОБАВЛЯТЬ: у компании
    # ровно одна организационно-правовая форма, и если источники называют
    # разные формы при похожем имени — это чаще всего два разных юрлица
    # (в долевом строительстве под объект или очередь регулярно заводят
    # отдельное ООО). Такой конфликт обязан попасть редактору, а не
    # схлопнуться молча: «ООО Единство» против «АО Единство» — расхождение,
    # даже если после снятия формы имя совпадает. Дешёвая сторона размена —
    # «ООО Единство» против голого «Единство» тоже станет расхождением
    # (никто явно не подтвердил, что это не два разных юрлица), это
    # осознанно: лишняя работа редактору дешевле молча применённой не той
    # фактуры.
    ORG_FORM_RX = /\A(?:гк|сз)\.?\s+/i

    module_function

    # @return [Array<String>] поля этого ЖК, по которым источники спорят
    def fields_for(complex)
      facts_by_field(ZhkFact.where(residential_complex_id: complex.id))
        .select { |_, facts| discrepant?(facts) }
        .keys
        .sort
    end

    # @return [Array<Hash>] для экрана админки, по всем ЖК сразу
    #
    # Факты, чей ЖК не резолвится, СНИМАЮТСЯ — и это решение, а не
    # умолчание. `ZhkFact` живёт независимо от карточки: `default_scope`
    # `ResidentialComplex` прячет мягко удалённые, поэтому у осиротевших
    # фактов `residential_complex` отдаёт `nil`, а вьюха зовёт
    # `row[:complex].display_name` — падала ВСЯ страница, а не одна
    # строка. Достижимость не теоретическая: мягко удалённый ЖК не
    # матчится, следующий обход заводит его заново, редактор удаляет
    # дубль снова — осиротевшие факты копятся штатным циклом чистки.
    #
    # Почему снимаем, а не тянем `unscoped`: экран — рабочая очередь по
    # карточкам, которые в справочнике ЕСТЬ. Вернуть сюда мягко удалённый
    # ЖК значило бы позвать редактора править то, что он сам осознанно
    # убрал, и заодно молча предрешить вопрос «матчер видит удалённых или
    # факты удаляются вместе с карточкой», записанный отдельной задачей до
    # боевого запуска. Эта правка не решает его, а лишь перестаёт ронять
    # экран.
    #
    # Потеря при этом НЕ молчаливая: снятые строки считаются и уходят в
    # лог — иначе расхождение исчезало бы с экрана без следа, а это тот
    # самый дорогой класс (пропавшее расхождение хуже лишнего, см.
    # докстринг модуля).
    def all
      orphaned = 0

      rows = facts_by_complex_and_field(ZhkFact.all)
             .filter_map do |(_complex_id, field), facts|
               next unless discrepant?(facts)

               complex = facts.first.residential_complex
               if complex.nil?
                 orphaned += 1
                 next
               end

               {
                 complex: complex,
                 field: field,
                 values: facts.map do |f|
                   { value: f.value, source: f.source, url: f.url, observed_at: f.observed_at }
                 end
               }
             end

      if orphaned.positive?
        Rails.logger.warn(
          "[Zhk::Discrepancies] снято #{orphaned} расхождений: карточка ЖК мягко удалена, факты осиротели"
        )
      end

      rows.sort_by { |row| [row[:complex].id, row[:field]] }
    end

    # @return [Boolean] спорит ли набор фактов одного поля между собой
    def discrepant?(facts)
      facts.map { |f| normalize(f.field, f.value) }.uniq.size > 1
    end
    private_class_method :discrepant?

    # @return [String] значение, приведённое к виду, годному для сравнения
    # (НЕ для сохранения — это чисто сравнение, сырое значение в `all` не
    # трогаем).
    def normalize(field, value)
      v = value.to_s.strip.gsub(/\s+/, ' ').downcase

      case field.to_s
      when 'developer'
        v = v.sub(ORG_FORM_RX, '')
      when 'built_from', 'built_to'
        # источники пишут год то голым числом, то с припиской «г.»/«год»,
        # то с кварталом впереди («4 кв. 2026», «IV кв. 2026» — римский
        # квартал цифр вообще не содержит, ему тут искать нечего). Год у
        # нас всегда 4 цифры — берём именно 4-значную группу, а НЕ первую
        # попавшуюся: `\d+` на «4 кв. 2026» против «4 кв. 2027» находил бы
        # квартал («4») и терял реальное расхождение в годе — так и было
        # поймано ревью круга правок 1.
        year = v[/\d{4}/]
        v = year if year
      end

      v
    end
    private_class_method :normalize

    def facts_by_field(scope)
      # `.order(:id)` — без него порядок строк внутри группы, а значит и
      # порядок `values` в `all`, ничем не гарантирован: Postgres волен
      # вернуть их в любом порядке без ORDER BY, и это ловилось бы не
      # каждый прогон.
      scope.where.not(value: nil).order(:id).group_by(&:field)
    end
    private_class_method :facts_by_field

    def facts_by_complex_and_field(scope)
      scope.where.not(value: nil)
           .order(:id)
           .includes(:residential_complex)
           .group_by { |f| [f.residential_complex_id, f.field] }
    end
    private_class_method :facts_by_complex_and_field
  end
end
