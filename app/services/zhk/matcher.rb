# frozen_string_literal: true

module Zhk
  # Сопоставление находки службы сбора с записью справочника.
  #
  # Сравнение идёт в Ruby, а не в SQL, намеренно: справочник это десятки
  # строк на город, а нормализация («ЖК», кавычки, ё, регистр) в SQL
  # превратилась бы в нечитаемое выражение, которое ещё и индекс не берёт.
  module Matcher
    PREFIX_RX = /\A\s*(жк|жилой\s+комплекс)\s+/i
    JUNK_RX   = /[^[:alnum:]]+/
    # «д.»/«дом» стрипаем ТОЛЬКО когда перед ними стоит запятая (с любым
    # числом пробелов вокруг) и сразу за ними — цифра. Граница здесь именно
    # запятая, а не пробел: формат адреса на проде запятыми разделён всегда
    # («Рязанская обл., г. Рязань, ДП, ул. Льговская, д. 10, кв. 469»), то
    # есть «,д.» — это позиционное поле адреса (номер дома), а не часть
    # названия улицы. Раньше правило было завязано на пробел после точки,
    # и это ловило не тот признак: «Красный Дом, 5» спасала от склейки с
    # «ул. Красный, 5» именно запятая ПОСЛЕ «Дом», а не пробел ПЕРЕД
    # цифрой — форма «ул. Красный Дом 5» без запятой проходила бы старое
    # правило и склеивалась. Опора на запятую закрывает обе стороны и
    # заодно принимает компактную нотацию без пробела («,д.1»).
    #
    # Осознанный размен в дешёвую сторону: «Есенина д. 1» без запятой
    # перед «д.» больше не стрипается (нет позиционной границы) — заведётся
    # черновик вместо автосвязки, это дешевле, чем случайная склейка.
    #
    # Список НЕ расширяем на «к»/«корп»/«стр»/«вл» — это не произвол:
    # «д. 5» и «5» действительно один и тот же дом, а «к. 5» — это корпус 5,
    # ДРУГОЙ адрес; стрип приравнял бы разные объекты.
    FILLER_AFTER_COMMA_RX = /(,\s*)(?:дом|д)\.?\s*(?=\d)/

    # Разделитель дроби номера дома («1/2», «6-8») между цифрами — часть
    # номера, а не пунктуация: если стереть его как обычный мусор (общий
    # JUNK_RX так и делает), «1/2» превращается в «1 2», и дом «1» из
    # дроби «1/2» совпадает по границе токена с отдельным домом №1 — хотя
    # это разные объекты. Именованная группа `fraction` отличает «эту /
    # или - между цифрами» от «любой другой мусор, включая одиночные / и -
    # не между цифрами» — по тому, какая альтернатива сработала, а не по
    # содержимому совпадения (оно у обеих одинаковое, один символ).
    FRACTION_OR_JUNK_RX = /(?<fraction>(?<=\d)[\/\-](?=\d))|[^[:alnum:]]+/

    module_function

    def call(name:, city:, address: nil)
      target = normalize(name)
      # Мусорное имя («ЖК .», пустая строка) нормализуется в '' — сравнивать
      # его с чем бы то ни было нельзя: в справочнике теоретически может
      # найтись запись, чьё название тоже схлопывается в '' (валидация
      # `presence: true` смотрит на исходную строку, а не на нормализованную).
      return nil if target.blank?

      # `not_deleted` здесь не снимаем и не дублируем через `unscoped`: без
      # него default_scope и так фильтрует мягко удалённые, но оставляем
      # явно — вызов не должен молча перестать быть безопасным, если
      # default_scope модели когда-нибудь изменится. `.order(:id)` — пул
      # без ORDER BY Postgres не гарантирует порядок; уникального индекса
      # на (city, name) нет, значит дубль с одинаковым нормализованным
      # именем в одном городе — состояние не запрещённое, и без
      # детерминированного порядка матчер «плавал» бы между карточками.
      pool = ResidentialComplex.not_deleted.in_city(city).order(:id).to_a

      by_name = pool.find { |c| normalize(c.name) == target }
      return by_name if by_name

      return nil if address.blank?

      # Два канала сопоставления сознательно НЕ симметричны по строгости.
      # Имя — полное равенство нормализованных строк: имя ЖК самодостаточно,
      # и наблюдение либо называет его целиком, либо это не совпадение.
      # Адрес — вхождение подстроки с границей токена: наблюдаемый адрес
      # почти всегда шире паттерна (город, квартира, подъезд, лишние слова
      # застройщика), и требовать полного равенства значило бы, что парсер
      # обязан дословно воспроизвести весь адрес — нереалистично.
      normalized_address = normalize_address_tokens(address)

      pool.find do |complex|
        Array(complex.address_patterns).compact_blank.any? do |pattern|
          normalized_pattern = normalize_address_tokens(pattern)
          normalized_pattern.present? && token_boundary_match?(normalized_pattern, normalized_address)
        end
      end
    end

    # «ЖК «ЛЕГЕНДА»» и «Легенда» — одно и то же; «Голландия. Парковый
    # квартал» и «Голландия Парковый квартал» — тоже.
    def normalize(value)
      value.to_s.downcase.tr('ё', 'е').sub(PREFIX_RX, '').gsub(JUNK_RX, ' ').strip.squeeze(' ')
    end

    # Своя нормализация вместо общей `normalize`: та же пунктуация/регистр/
    # ё-е и позиционное снятие «д.»/«дом» после запятой (FILLER_AFTER_COMMA_RX),
    # но junk-коллапс — через FRACTION_OR_JUNK_RX, который сохраняет «/»/«-»
    # между цифрами вместо общего JUNK_RX, стирающего всё подряд.
    def normalize_address_tokens(value)
      text = value.to_s.downcase.tr('ё', 'е').gsub(FILLER_AFTER_COMMA_RX, '\1').sub(PREFIX_RX, '')
      text.gsub(FRACTION_OR_JUNK_RX) { Regexp.last_match(:fraction) || ' ' }.strip.squeeze(' ')
    end

    # Вхождение `pattern` в `text` как последовательности токенов, а не
    # произвольной подстроки: сразу перед и сразу после найденного куска не
    # должно быть буквы/цифры — ИЛИ «/»/«-»: они тоже продолжение номера
    # дома (см. FRACTION_OR_JUNK_RX), а не разделитель. Без этого расширения
    # полное имя «есенина 1» совпало бы с началом «есенина 1/2» — после «1»
    # там уже не цифра, но дом всё ещё тот же самый объект «1/2», не «1».
    # Обе строки уже нормализованы (единственный пробел между словами),
    # поэтому lookaround на границах — самый короткий способ выразить «это
    # отдельные слова, а не обрезок более длинного» без ручного разбора на
    # токены и посимвольного поиска.
    def token_boundary_match?(pattern, text)
      Regexp.new("(?<![[:alnum:]\\/\\-])#{Regexp.escape(pattern)}(?![[:alnum:]\\/\\-])").match?(text)
    end
  end
end
