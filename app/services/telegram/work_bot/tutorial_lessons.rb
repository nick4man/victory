      module_function

      # @return [Array<Hash>] уроки, доступные этому сотруднику, в порядке прохождения.
      def visible_for(tg_user)
        LESSONS.select { |lesson| level_ok?(tg_user, lesson[:min_level]) }
      end

      # @param tg_user [TelegramUser, nil]
      # @param min_level [Symbol] :staff | :manager | :director
      def level_ok?(tg_user, min_level)
        return false if tg_user.nil?

        case min_level
        when :staff then true
        when :manager then tg_user.manager_or_director?
        when :director then tg_user.can_voice_distribute?
        else false
        end
      end
    end
