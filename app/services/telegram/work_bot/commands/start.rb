# frozen_string_literal: true

module Telegram
  module WorkBot
    module Commands
      # `/start` — первое, что видит новый сотрудник. Раньше здесь открывался
      # полный справочник команд, включая чужие роли: человек получал простыню
      # вместо понятного «что делать». Теперь короткое приветствие и меню
      # «Что сделать?» с кнопками; полный список остался в /help.
      class Start < Menu
        public_command

        def handle
          # Команда публичная, значит сюда доходит и тот, кого бот ещё не знает:
          # Menu на таком падал бы на nil. Ему — как привязаться, а не меню.
          if tg_user.nil?
            reply('👋 Это рабочий бот АН «Виктори». Привяжи свой рабочий email: ' \
                  '<code>/whoami email@victory62.org</code> — и появится меню.')
            return :not_linked
          end

          dm('👋 Это рабочий бот АН «Виктори». Ниже — что можно сделать; ' \
             'полный список команд — /help.')
          super
        end
      end
    end
  end
end
