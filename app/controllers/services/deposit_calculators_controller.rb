# frozen_string_literal: true

module Services
  # Депозитный калькулятор — выделен из единой страницы калькулятора
  # ипотеки, чтобы навигация раздела «Финансы» вела на разные адреса
  # (а не три кнопки в дропдауне на одну страницу).
  #
  # Загружает: курируемый список депозитных программ
  # (`Deposit::ProgramsService.all`, который сам читает из последнего
  # OK-снимка banki.ru, fallback на хардкод-константу) + макро-ставки ЦБ
  # для блока контекста.
  class DepositCalculatorsController < ApplicationController
    def show
      @macro            = safe_macro
      @deposit_programs = Deposit::ProgramsService.all
      @faq              = faq_items

      set_meta_tags(
        title:       'Депозитный калькулятор — рассчитайте доход от вклада',
        description: 'Рассчитайте доход от вклада с учётом капитализации и сравните ' \
                     'ставки крупнейших банков. Источник — еженедельный snapshot ' \
                     'banki.ru. Бесплатно, без регистрации.',
        keywords:    'депозитный калькулятор, вклад, доход вклада, ставка депозита, банки рязань',
        canonical:   request.url.split('?').first
      )
    end

    private

    def safe_macro
      MacroRatesService.call
    rescue StandardError => e
      Rails.logger.warn("[DepositCalculators#show] macro fetch failed: #{e.class}: #{e.message}")
      { key_rate: 16.0, deposit_rate: 15.0, mortgage_rate: 22.0, source: 'fallback (ЦБ РФ)' }
    end

    def faq_items
      [
        { q: 'Что такое капитализация процентов?',
          a: 'Капитализация — это начисление процентов не только на изначальную сумму вклада, но и на ранее начисленные проценты. С капитализацией итоговая доходность выше: эффективная ставка превышает номинальную.' },
        { q: 'В чём разница между ставкой и эффективной ставкой?',
          a: 'Номинальная ставка — это процент, который банк обещает за год. Эффективная — реальная годовая доходность с учётом капитализации. Например, при номинальной 16% с ежемесячной капитализацией эффективная будет ~17,2%.' },
        { q: 'Чем отличается вклад от накопительного счёта?',
          a: 'Вклад — фиксированный срок и ставка, досрочное снятие обычно с потерей процентов. Накопительный счёт — без срока, ставка может меняться, можно свободно снимать и пополнять, но условия по доходности обычно хуже.' },
        { q: 'Какие гарантии возврата средств?',
          a: 'Вклады до 1,4 млн ₽ застрахованы Агентством по страхованию вкладов (АСВ). При отзыве лицензии у банка АСВ выплачивает страховку в течение 14 дней.' },
        { q: 'Что выгоднее — депозит или ипотека?',
          a: 'Зависит от ваших целей. На странице «Вклад vs Ипотека» мы посчитаем оба сценария на ваших цифрах за 20 лет с учётом роста стоимости квартиры и роста аренды.' }
      ]
    end
  end
end
