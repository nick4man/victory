# frozen_string_literal: true

require 'rails_helper'

RSpec.describe Zhk::CatalogHints do
  it 'находит ЖК, названный в карточке, но отсутствующий в справочнике' do
    create(:property, title: 'Квартира в ЖК «Небывалый»',
                      address: 'Рязанская обл., г. Рязань, ул. Новая, д. 1')

    hint = described_class.call.first

    expect(hint[:name]).to eq('Небывалый')
    expect(hint[:sample_address]).to include('ул. Новая')
  end

  it 'молчит про ЖК, который уже заведён' do
    create(:residential_complex, name: 'Легенда', city: 'Рязань')
    create(:property, title: 'Квартира в ЖК «Легенда»',
                      address: 'Рязанская обл., г. Рязань, ул. Интернациональная, д. 20')

    expect(described_class.call).to be_empty
  end

  it 'схлопывает несколько карточек одного ЖК в одну подсказку' do
    create(:property, title: 'Однушка в ЖК «Небывалый»', address: 'Рязань, ул. Новая, д. 1')
    create(:property, title: 'Двушка в ЖК «Небывалый»', address: 'Рязань, ул. Новая, д. 3')

    expect(described_class.call.size).to eq(1)
    expect(described_class.call.first[:property_ids].size).to eq(2)
  end

  it 'не принимает за название оборот речи' do
    create(:property, title: 'Рядом с ЖК и остановкой', address: 'Рязань, ул. Новая, д. 5')

    expect(described_class.call).to be_empty
  end

  it 'не принимает за название оборот речи, даже если он начат с заглавной буквы' do
    # Регэксп сам по себе такое захватывает: слово сразу после «ЖК»
    # написано с заглавной (как если бы предложение или рекламный текст
    # начинались отсюда) и удовлетворяет форме имени. Отсекает именно
    # STOP_WORDS — без него тест ниже не проходит.
    create(:property, title: 'ЖК Рядом с остановкой, отличный выбор',
                      address: 'Рязань, ул. Новая, д. 11')

    expect(described_class.call).to be_empty
  end

  it 'не возвращает мягко удалённый ЖК как подсказку' do
    # Редактор осознанно удалил ЖК — Matcher.call для него отдаёт nil
    # (не отличить от «никогда не существовал»), поэтому CatalogHints
    # обязан проверять реестр мягко удалённых отдельно, а не полагаться
    # только на Matcher.
    create(:residential_complex, :soft_deleted, name: 'Скрытый', city: 'Рязань')
    create(:property, title: 'Квартира в ЖК «Скрытый»',
                      address: 'Рязанская обл., г. Рязань, ул. Дачная, д. 2')

    expect(described_class.call).to be_empty
  end

  it 'отсеивает однобуквенное и числовое «название»' do
    create(:property, title: 'ЖК А, кв. 12', address: 'Рязань, ул. Новая, д. 7')
    create(:property, title: 'Сдача в ЖК 2026 году', address: 'Рязань, ул. Новая, д. 9')

    expect(described_class.call).to be_empty
  end

  it 'не теряет настоящую находку из-за случайного адресного совпадения на другой карточке с тем же именем' do
    # Круг правок 1: кэш вердикта матчера по (город, имя) БЕЗ адреса
    # заставлял решение по одной карточке (совпадение по адресу с чужим
    # ЖК) применяться ко всем карточкам с тем же именем — даже к тем,
    # чей адрес с этим паттерном никак не пересекается.
    create(:residential_complex, name: 'Легенда', city: 'Рязань',
                                 address_patterns: ['Костычева, 8'])

    # Имя «Стройка» не заведено нигде, но адрес этой карточки случайно
    # попадает в address_pattern чужого ЖК — матчер по адресу найдёт
    # «Легенду», и это ПРАВИЛЬНО должно скрыть именно эту карточку.
    coincidence = create(:property, title: 'Квартира в ЖК «Стройка»',
                                    address: 'Рязанская обл., г. Рязань, ул. Костычева, д. 8, кв. 5')
    # То же имя, но другой адрес — настоящая незаведённая находка,
    # адресный паттерн «Легенды» её не задевает.
    real_find = create(:property, title: 'Квартира в ЖК «Стройка»',
                                  address: 'Рязанская обл., г. Рязань, ул. Есенина, д. 20')

    hints = described_class.call

    expect(hints.size).to eq(1)
    expect(hints.first[:name]).to eq('Стройка')
    expect(hints.first[:property_ids]).to contain_exactly(real_find.id)
    expect(hints.first[:property_ids]).not_to include(coincidence.id)
  end

  it 'находит имя без кавычек в самом конце текста, оканчивающееся точкой' do
    # Круг правок 2: без конца строки как законного терминатора такое имя
    # не матчилось вовсе — после точки конца предложения не было ни
    # запятой, ни кавычки, ни переноса строки, а сама точка терминатором
    # не считается (иначе резались бы составные имена, круг правок 1).
    create(:property, title: 'Квартира в ЖК Северный.', description: nil,
                      address: 'Рязань, ул. Новая, д. 13')

    hint = described_class.call.first

    expect(hint[:name]).to eq('Северный')
  end

  it 'не режет составное имя по внутренней точке и не путает его с уже заведённым' do
    # Круг правок 1: точка внутри класса терминаторов останавливала
    # ленивый разбор на первой внутренней точке составного имени —
    # «Голландия. Парковый квартал» превращалась в «Голландия», для
    # которой матчер (заслуженно) не находил совпадения, и уже заведённый
    # ЖК ложно попадал в подсказки как новый.
    create(:residential_complex, name: 'Голландия. Парковый квартал', city: 'Рязань')

    create(:property, title: 'Квартира в ЖК «Голландия. Парковый квартал»',
                      address: 'Рязанская обл., г. Рязань, ул. Зубковой, д. 3')

    expect(described_class.call).to be_empty
  end

  it 'находит составное имя, разорванное переносом строки, даже если его первая часть уже заведена' do
    # Круг правок 3: `\n` входил и в тело имени (через `\s`), и в класс
    # терминаторов — та же конструкция, что была с точкой в кругах 1-2,
    # просто с другим символом. «Речной\nПорт» резалось на «Речной»,
    # обрубок совпадал с уже заведённым «Речной», и находка про «Речной
    # Порт» пропадала целиком, а не просто искажалась.
    create(:residential_complex, name: 'Речной', city: 'Рязань')

    property = create(:property, title: 'Квартира у воды', description: "Уютная квартира в ЖК Речной\nПорт, вид на воду",
                                 address: 'Рязанская обл., г. Рязань, наб. Приокская, д. 4')

    hints = described_class.call

    expect(hints.size).to eq(1)
    expect(hints.first[:name]).to eq('Речной Порт')
    expect(hints.first[:property_ids]).to contain_exactly(property.id)
  end

  it 'ограничивает слипание с соседней фразой длиной — не тянет всё описание' do
    # Побочный эффект схлопывания переносов строк в пробел: имя без знака
    # препинания перед переносом строки склеивается с началом следующей
    # фразы. Верхняя граница `{2,40}` обязана остановить это раньше, чем
    # регэксп утянет половину описания — иначе размен перестаёт быть
    # безопасным.
    long_tail = 'Отличная планировка просторная кухня закрытый двор рядом парк озеро лес прекрасный вид с балкона'
    create(:property, title: "Квартира в ЖК Северный\n#{long_tail}", description: nil,
                      address: 'Рязанская обл., г. Рязань, ул. Новая, д. 15')

    expect(described_class.call).to be_empty
  end
end
